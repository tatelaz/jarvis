def main(words: list[str]) -> int:
    """words: solo le mutazioni la cui descrizione contiene una di queste parole (nessuna = tutte)."""
    chosen = [m for m in MUTATIONS if not words or any(w.lower() in m[4].lower() for w in words)]
    survived = []
    for rel, old, new, test, desc in chosen:
        path = ROOT / rel
        raw = path.read_bytes()  # ripristino byte per byte: write_text su Windows trasformerebbe LF in CRLF
        src = raw.decode("utf-8").replace("\r\n", "\n")
        if old not in src:
            print(f"!! mutazione non applicabile ({desc}): testo non trovato in {rel}")
            survived.append(desc)
            continue
        path.write_bytes(src.replace(old, new, 1).encode("utf-8"))
        try:
            r = subprocess.run([PY, "-m", "pytest", "-q", "-x", test], cwd=ROOT, capture_output=True, text=True)
        finally:
            path.write_bytes(raw)
        caught = r.returncode != 0
        print(f"{'colta   ' if caught else 'SFUGGITA'}  {desc}")
        if not caught:
            survived.append(desc)
    print(f"\n{len(chosen) - len(survived)}/{len(chosen)} mutazioni colte")
    return 1 if survived else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
